"""Static salary data.

Two distinct things live here:

1. DEFAULT salary tables (rank -> salary). These are the authoritative tables
   from LEAGUE_MECHANICS.md §12 and drive the post-race salary adjustment
   engine. Do not edit — they encode the published formula.

2. Season-start rankings. Per §12.5 starting salaries are a manual,
   staff-set input, not generated by the formula. We rank the grid by the
   previous season's final championship standings and read the default table
   at each rank. Drivers and teams are keyed by stable identity — the
   3-letter driver code and the OpenF1 ``team_name`` — because driver numbers
   change between seasons (e.g. the champion takes #1).

   For a league that joins mid-season, these are round-1 salaries; replaying
   the completed races through the salary engine brings them up to date.
"""

# --- Authoritative default tables (LEAGUE_MECHANICS.md §12) -----------------
# Drivers: 1st = £34M, −£1.6M per rank, floor £400k at P22.
DRIVER_DEFAULT_SALARY = {
    1: 34_000_000, 2: 32_400_000, 3: 30_800_000, 4: 29_200_000,
    5: 27_600_000, 6: 26_000_000, 7: 24_400_000, 8: 22_800_000,
    9: 21_200_000, 10: 19_600_000, 11: 18_000_000, 12: 16_400_000,
    13: 14_800_000, 14: 13_200_000, 15: 11_600_000, 16: 10_000_000,
    17: 8_400_000, 18: 6_800_000, 19: 5_200_000, 20: 3_600_000,
    21: 2_000_000, 22: 400_000,
}

# Constructors: 1st = £30M, −£2.6M per rank, floor £4M at P11.
CONSTRUCTOR_DEFAULT_SALARY = {
    1: 30_000_000, 2: 27_400_000, 3: 24_800_000, 4: 22_200_000,
    5: 19_600_000, 6: 17_000_000, 7: 14_400_000, 8: 11_800_000,
    9: 9_200_000, 10: 6_600_000, 11: 4_000_000,
}

DRIVER_SALARY_FLOOR = DRIVER_DEFAULT_SALARY[22]
CONSTRUCTOR_SALARY_FLOOR = CONSTRUCTOR_DEFAULT_SALARY[11]

# --- Season-start rankings ----------------------------------------------------
# 2026: 2025 final championship order (OpenF1 championship standings after the
# Abu Dhabi GP), restricted to the 2026 grid. Drivers new to the grid follow in
# the order listed. Kick Sauber became Audi; Cadillac is a new entry.
STARTING_DRIVER_RANKING: dict[int, list[str]] = {
    2026: [
        "NOR", "VER", "PIA", "RUS", "LEC", "HAM", "ANT", "ALB", "SAI", "ALO",
        "HUL", "HAD", "BEA", "LAW", "OCO", "STR", "GAS", "BOR", "COL",
        "PER", "BOT", "LIN",  # not on the 2025 grid
    ],
}

STARTING_CONSTRUCTOR_RANKING: dict[int, list[str]] = {
    2026: [
        "McLaren", "Mercedes", "Red Bull Racing", "Ferrari", "Williams",
        "Racing Bulls", "Aston Martin", "Haas F1 Team", "Audi", "Alpine",
        "Cadillac",
    ],
}


def starting_driver_salary(season: int, code: str | None) -> int:
    """Season-start salary for a driver by code; the floor if unranked."""
    ranking = STARTING_DRIVER_RANKING.get(season, [])
    if code in ranking:
        return DRIVER_DEFAULT_SALARY.get(ranking.index(code) + 1, DRIVER_SALARY_FLOOR)
    return DRIVER_SALARY_FLOOR


def starting_constructor_salary(season: int, team_name: str) -> int:
    """Season-start salary for a team by name; the floor if unranked."""
    ranking = STARTING_CONSTRUCTOR_RANKING.get(season, [])
    if team_name in ranking:
        return CONSTRUCTOR_DEFAULT_SALARY.get(
            ranking.index(team_name) + 1, CONSTRUCTOR_SALARY_FLOOR
        )
    return CONSTRUCTOR_SALARY_FLOOR
